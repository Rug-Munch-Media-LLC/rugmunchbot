"""Public trade-flow evidence for one open market.

What this module does NOT do: it does not score wallets, does not infer intent,
does not name people, and does not claim coordination. It reports three public
observations:

  1. large taker trades (notional = shares x price) above a threshold;
  2. wallets with a low all-time market count (``/traded``), which is a count,
     not an identity;
  3. several distinct wallets taking the same outcome in the sampled window,
     which is concentration of public flow, not proof of a cluster.

Wording in the card is generated by :mod:`rugmunchbot.polymarket.card`.
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Any

from rugmunchbot.polymarket.models import FlowEvidence, FlowTrade


def _num(value: Any) -> float | None:
    if value is None or value == "":
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def _utc(ts: int) -> str:
    return datetime.fromtimestamp(ts, tz=UTC).strftime("%Y-%m-%d %H:%M UTC")


def build_flow_evidence(
    condition_id: str,
    raw_trades: list[dict[str, Any]],
    traded_counts: dict[str, int | None],
    *,
    min_notional_usd: float = 10_000.0,
    low_history_max_markets: int = 5,
    max_trades: int = 5,
) -> FlowEvidence:
    """Build evidence from raw public trades. Never raises on junk rows."""
    trades: list[FlowTrade] = []
    for row in raw_trades:
        if not isinstance(row, dict):
            continue
        shares = _num(row.get("size"))
        price = _num(row.get("price"))
        wallet = str(row.get("proxyWallet") or "").strip()
        ts = row.get("timestamp")
        if shares is None or price is None or not wallet or not isinstance(ts, int):
            continue
        notional = shares * price
        if notional < min_notional_usd:
            continue
        trades.append(
            FlowTrade(
                wallet=wallet,
                side=str(row.get("side") or "").upper(),
                outcome=str(row.get("outcome") or ""),
                shares=shares,
                price=price,
                notional_usd=round(notional, 2),
                timestamp=ts,
                tx_hash=str(row.get("transactionHash") or ""),
            )
        )

    trades.sort(key=lambda t: t.notional_usd, reverse=True)
    total = round(sum(t.notional_usd for t in trades), 2)

    low_history = tuple(
        sorted(
            {
                t.wallet
                for t in trades
                if (count := traded_counts.get(t.wallet)) is not None
                and count <= low_history_max_markets
            }
        )
    )

    by_outcome: dict[str, set[str]] = {}
    for trade in trades:
        by_outcome.setdefault(trade.outcome, set()).add(trade.wallet)
    concentration = tuple(
        sorted(
            {wallet for wallets in by_outcome.values() if len(wallets) >= 3 for wallet in wallets}
        )
    )

    window_note = ""
    if trades:
        stamps = [t.timestamp for t in trades]
        window_note = (
            f"Observed in public trades from {_utc(min(stamps))} to {_utc(max(stamps))} "
            f"({len(trades)} taker trades at or above ${min_notional_usd:,.0f}, sampled not exhaustive)."
        )

    return FlowEvidence(
        condition_id=condition_id,
        trades=tuple(trades[:max_trades]),
        low_history_wallets=low_history,
        same_outcome_wallets=concentration,
        total_notional_usd=total,
        window_note=window_note,
    )
